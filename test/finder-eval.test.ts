/** Skill finder eval harness (scripts/skill-finder-eval.mjs). Invented transcripts and invented skills only: no owner transcript is read here. */
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tempDir } from './tmp-cleanup.js';

const REPO = fileURLToPath(new URL('../../', import.meta.url));
const SCRIPT = join(REPO, 'scripts', 'skill-finder-eval.mjs');
const FIXTURES = fileURLToPath(new URL('../../test/fixtures/skill-finder/', import.meta.url));

interface Sandbox { base: string; privateRoot: string; home: string; claude: string }

/** One temp tree per test: a fake Legion home, a fake Claude home and a private root the script may write under. */
function sandbox(): Sandbox {
  const base = tempDir('skill-finder-eval-');
  const sb = { base, privateRoot: join(base, 'private'), home: join(base, 'legion-home'), claude: join(base, 'claude-home') };
  for (const d of [sb.privateRoot, sb.home, sb.claude]) mkdirSync(d, { recursive: true });
  return sb;
}

function run(sb: Sandbox, args: string[]): { status: number | null; out: string } {
  const r = spawnSync(process.execPath, [SCRIPT, ...args], {
    cwd: REPO,
    encoding: 'utf8',
    timeout: 120_000,
    env: { ...process.env, LEGION_HOME: sb.home, CLAUDE_CONFIG_DIR: sb.claude, SKILL_FINDER_PRIVATE_ROOT: sb.privateRoot },
  });
  return { status: r.status, out: `${r.stdout}\n${r.stderr}` };
}

const user = (content: unknown, extra: Record<string, unknown> = {}) => ({ type: 'user', message: { role: 'user', content }, ...extra });
const call = (skill: string, extra: Record<string, unknown> = {}) => ({
  type: 'assistant',
  message: { role: 'assistant', content: [{ type: 'tool_use', id: 'toolu_x', name: 'Skill', input: { skill } }] },
  ...extra,
});

function writeJsonl(path: string, rows: unknown[]): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, rows.map((r) => (typeof r === 'string' ? r : JSON.stringify(r))).join('\n') + '\n');
}

function readRows(path: string): Array<Record<string, unknown>> {
  return readFileSync(path, 'utf8').split('\n').filter((l) => l.trim() !== '').map((l) => JSON.parse(l) as Record<string, unknown>);
}

/** A transcript tree with one line of every kind the build must skip, and the rows it must keep. */
function writeTranscripts(base: string): string {
  const root = join(base, 'transcripts');
  writeJsonl(join(root, 'alpha', 'beta', 'session-a.jsonl'), [
    user('Run a widget-audit on the storefront pages', { promptSource: 'typed', turnOrigin: 'human' }),
    call('widget-audit'),
    user('Plan the garden layout for spring'),
    call('acme:garden-planner'),
    user('Routine check-in text', { promptSource: 'system' }),
    user('Task finished in the background', { turnOrigin: 'task_notification' }),
    user('Please look at the invoice totals', { isSidechain: true }),
    user('Peer message about the order queue', { turnOrigin: 'peer' }),
    user([{ type: 'tool_result', tool_use_id: 'toolu_x', content: 'ok' }]),
    user('<command-name>/clear</command-name>'),
    user('<system-reminder>Reminder only</system-reminder>'),
    user('Caveat: The messages below were generated by the user while running local commands. Ignore them.'),
    '{not json',
    user('/widget-audit now for the blog'),
    call('widget-audit'),
    user('/garden-planner plan the beds'),
    call('acme:garden-planner'),
    user('Check the storefront banner'),
    { ...call('widget-audit'), isSidechain: true },
  ]);
  writeJsonl(join(root, 'gamma', 'session-b.jsonl'), [
    user('Draft a note about the bot lineup', { turnOrigin: 'sdk', promptSource: 'sdk' }),
    user([
      { type: 'image', source: {} },
      { type: 'text', text: '<system-reminder>Context</system-reminder>\nWrite the widget-audit summary' },
    ]),
    call('widget-audit'),
    call('widget-audit'),
    user('Check the storefront banner'),
  ]);
  return root;
}

// A subagent's Skill call (sidechain line) pairs with the owner's last real prompt, like any other call.
const SET_A = [
  { prompt: 'Run a widget-audit on the storefront pages', skill: 'widget-audit', subset: 'named' },
  { prompt: 'Plan the garden layout for spring', skill: 'acme:garden-planner', subset: 'implicit' },
  { prompt: 'Check the storefront banner', skill: 'widget-audit', subset: 'implicit' },
  { prompt: 'Write the widget-audit summary', skill: 'widget-audit', subset: 'named' },
];
const PROMPT_TEXTS = [
  'Run a widget-audit', 'Plan the garden', 'Routine check-in', 'Task finished', 'invoice totals', 'Peer message',
  'Reminder only', 'Caveat: The messages', 'command-name', '/widget-audit now', '/garden-planner', 'Check the storefront banner',
  'Draft a note', 'Write the widget-audit summary',
];

describe('finder eval: build', () => {
  it('writes the gold set and skips harness, sidechain, typed and malformed lines', () => {
    const sb = sandbox();
    const out = join(sb.privateRoot, 'gold');
    const r = run(sb, ['build', '--transcripts', writeTranscripts(sb.base), '--out', out]);
    assert.equal(r.status, 0, r.out);
    assert.deepEqual(readRows(join(out, 'setA.jsonl')), SET_A);
    const negatives = readRows(join(out, 'negatives.jsonl')).map((n) => n.prompt);
    // 'Check the storefront banner' has a call (in the sidechain) and is also in file b with no call: it is not a negative.
    assert.deepEqual(negatives, ['Draft a note about the bot lineup']);
    for (const text of PROMPT_TEXTS) assert.ok(!r.out.includes(text), `stdout or stderr printed prompt text: ${text}`);
  });

  it('caps negatives at 300 and writes the same bytes on a second run', () => {
    const sb = sandbox();
    const filler = join(sb.base, 'filler', 'session.jsonl');
    writeJsonl(filler, Array.from({ length: 320 }, (_, i) => user(`Filler prompt number ${i}`)));
    const a = join(sb.privateRoot, 'a');
    const b = join(sb.privateRoot, 'b');
    assert.equal(run(sb, ['build', '--transcripts', join(sb.base, 'filler'), '--out', a]).status, 0);
    assert.equal(run(sb, ['build', '--transcripts', join(sb.base, 'filler'), '--out', b]).status, 0);
    assert.equal(readRows(join(a, 'negatives.jsonl')).length, 300);
    assert.equal(readFileSync(join(a, 'negatives.jsonl'), 'utf8'), readFileSync(join(b, 'negatives.jsonl'), 'utf8'));
  });

  it('refuses an out folder outside the private folder before it reads a transcript', () => {
    const sb = sandbox();
    const transcripts = writeTranscripts(sb.base);
    const refused = [join(sb.base, 'outside'), join(sb.privateRoot, '..', 'escape'), `${sb.privateRoot}-evil`];
    for (const out of refused) {
      const r = run(sb, ['build', '--transcripts', transcripts, '--out', out]);
      assert.equal(r.status, 1, out);
      assert.match(r.out, /inside/);
      assert.equal(existsSync(out), false, `refused run wrote ${out}`);
    }
    assert.equal(existsSync(join(sb.base, 'escape')), false);
    const missing = run(sb, ['build', '--transcripts', join(sb.base, 'no-such-dir'), '--out', refused[0]]);
    assert.match(missing.out, /inside/, 'the folder check must run before the transcript check');
    const inside = join(sb.privateRoot, 'nested', 'ok');
    assert.equal(run(sb, ['build', '--transcripts', transcripts, '--out', inside]).status, 0);
    assert.ok(existsSync(join(inside, 'setA.jsonl')));
  });
});

describe('finder eval: score', () => {
  it('scores the public fixture and writes the report shape to --json', () => {
    const sb = sandbox();
    const jsonPath = join(sb.base, 'fixture-report.json');
    const setPath = join(FIXTURES, 'cases.jsonl');
    const r = run(sb, ['score', '--set', setPath, '--catalog', join(FIXTURES, 'skills.json'), '--json', jsonPath]);
    assert.equal(r.status, 0, r.out);
    const report = JSON.parse(readFileSync(jsonPath, 'utf8')) as Record<string, any>;
    assert.equal(report.catalog.skills, 12);
    assert.equal(report.set.cases, 30);
    for (const key of ['recall1', 'recall3', 'recall5', 'mrr5']) assert.equal(typeof report.set[key], 'number', key);
    assert.ok(report.set.recall5 > 0, 'the fixture must find something');
    assert.equal(report.negatives, null);
    assert.equal(report.perSkill.length, 12);
    assert.equal(typeof report.latency.p95Ms, 'number');
    const firstPrompt = JSON.parse(readFileSync(setPath, 'utf8').split('\n')[0]!).prompt as string;
    assert.ok(!r.out.includes(firstPrompt), 'score printed a prompt');
  });

  it('counts a negative that gets a note as a false note', () => {
    const sb = sandbox();
    const negPath = join(sb.base, 'negatives.jsonl');
    writeJsonl(negPath, [{ prompt: 'zebra quartz nebula' }, { prompt: 'Descale the kettle with citric acid' }]);
    const jsonPath = join(sb.base, 'neg-report.json');
    const r = run(sb, ['score', '--set', join(FIXTURES, 'cases.jsonl'), '--negatives', negPath, '--catalog', join(FIXTURES, 'skills.json'), '--json', jsonPath]);
    assert.equal(r.status, 0, r.out);
    const report = JSON.parse(readFileSync(jsonPath, 'utf8')) as Record<string, any>;
    assert.equal(report.negatives.count, 2);
    assert.equal(report.negatives.falseNotes, 1);
    assert.equal(report.negatives.falseNoteRate, 0.5);
  });

  it('refuses an unknown threshold and a k outside 1 to 5', () => {
    const sb = sandbox();
    const setPath = join(FIXTURES, 'cases.jsonl');
    const catalog = join(FIXTURES, 'skills.json');
    const loud = run(sb, ['score', '--set', setPath, '--catalog', catalog, '--threshold', 'loud']);
    assert.equal(loud.status, 1);
    assert.match(loud.out, /--threshold/);
    const big = run(sb, ['score', '--set', setPath, '--catalog', catalog, '--k', '9']);
    assert.equal(big.status, 1);
    assert.match(big.out, /--k/);
  });

  it('reads the legion catalog from LEGION_HOME and writes nothing there', () => {
    const sb = sandbox();
    const jsonPath = join(sb.base, 'legion-report.json');
    const r = run(sb, ['score', '--set', join(FIXTURES, 'cases.jsonl'), '--catalog', 'legion', '--json', jsonPath]);
    assert.equal(r.status, 0, r.out);
    const report = JSON.parse(readFileSync(jsonPath, 'utf8')) as Record<string, any>;
    assert.equal(report.catalog.source, 'legion');
    assert.deepEqual(readdirSync(sb.home), []);
  });
});
