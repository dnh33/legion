// Inlines the takeover animation (src/shared/takeover-art.ts) into assets/splash.html, between the two marker comments.
// The splash is a static file whose CSP allows only inline script, so it cannot import the module: this bundles it with esbuild
// (already present through vite) into one inline <script>. test/takeover-splash.test.ts re-bundles and fails if the splash drifted.
// Usage: node scripts/gen-splash-art.mjs   (rerun after any change to src/shared/takeover-art.ts)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SPLASH = join(ROOT, 'assets', 'splash.html');
export const START = '<!-- takeover-art:start (generated by scripts/gen-splash-art.mjs, do not edit) -->';
export const END = '<!-- takeover-art:end -->';

/** The inline block: the module as an IIFE on window.LegionTakeover. */
export async function bundle() {
  const esbuild = await import(pathToFileURL(join(ROOT, 'node_modules', 'esbuild', 'lib', 'main.js')).href);
  const out = await esbuild.build({
    stdin: {
      contents: "export { frameAt, stillFrame, progressBar, BOOT, CANVAS_W, CANVAS_H } from './src/shared/takeover-art.ts';",
      resolveDir: ROOT, loader: 'ts', sourcefile: 'takeover-entry.ts',
    },
    bundle: true, format: 'iife', globalName: 'LegionTakeover', minify: true, target: 'es2020', charset: 'utf8',
    legalComments: 'none', write: false, logLevel: 'silent',
  });
  return `${START}\n<script>${out.outputFiles[0].text.trim()}</script>\n${END}`;
}

/** The block currently in splash.html, or null when the markers are missing. */
export function current(html = readFileSync(SPLASH, 'utf8')) {
  const a = html.indexOf(START), b = html.indexOf(END);
  return a < 0 || b < a ? null : html.slice(a, b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const html = readFileSync(SPLASH, 'utf8');
  const old = current(html);
  if (!old) { console.error('[gen-splash-art] markers not found in assets/splash.html'); process.exit(1); }
  const next = await bundle();
  if (next === old) { console.log('[gen-splash-art] up to date'); process.exit(0); }
  writeFileSync(SPLASH, html.replace(old, () => next)); // a function: minified code may contain "$&" or "$1"
  console.log(`[gen-splash-art] wrote ${next.length} bytes into assets/splash.html`);
}
